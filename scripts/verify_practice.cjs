const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const target = process.env.TUTORIAL_URL || 'http://127.0.0.1:60436/';
const expected = require('../docs/exercises.json').exercises.filter(e=>e.source_kind==='dialogue_round');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PROXY?{proxy:{server:process.env.BROWSER_PROXY}}:{})});
  try {
    const page=await browser.newPage({viewport:{width:1280,height:900}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const drill=expected.find(e=>e.round_id==='BV1vj6yBDE5r-q002');
    assert.ok(drill);
    const response=await page.goto(target+'#exercise='+encodeURIComponent(drill.id),{waitUntil:'networkidle',timeout:60000});
    assert.equal(response.status(),200);
    assert.equal(await page.locator('#practice-panel').isVisible(),true);
    assert.equal(await page.locator('#practice-exercise').inputValue(),drill.id);
    assert.equal(await page.locator('#practice-answer').isVisible(),false);
    assert.equal(await page.locator('#practice-answer .sample-response').isVisible(),false);
    await page.locator('#practice-draft').fill('我会先确认你的偏好，再商量自己的安排。');
    await page.locator('#reveal-answer').click();
    assert.equal(await page.locator('#practice-answer').isVisible(),true);
    assert.equal(await page.locator('#practice-answer .sample-response').innerText(),drill.response);
    assert.match(await page.locator('#practice-answer').innerText(),/原创建议|自己的答案/);
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await page.locator('#practice-draft').inputValue(),'我会先确认你的偏好，再商量自己的安排。');
    assert.equal(await page.locator('#practice-answer').isVisible(),true);
    const sourceLink=await page.locator('#exercise-detail .round-source a').first().getAttribute('href');
    const source=new URL(sourceLink);assert.equal(source.searchParams.get('t'),String(Math.floor(drill.source_time_seconds)));
    await page.locator('#next-exercise').click();
    assert.notEqual(await page.locator('#practice-exercise').inputValue(),drill.id);
    await page.selectOption('#practice-episode','all');
    await page.selectOption('#practice-quality','all');
    assert.equal(await page.locator('#practice-exercise option').count(),expected.length);
    await page.selectOption('#practice-quality','pending');
    assert.equal(await page.locator('#practice-exercise option').count(),expected.filter(e=>e.practice_status==='pending').length);
    await page.selectOption('#practice-source','legacy');
    assert.equal(await page.locator('#practice-exercise option').count(),26);
    await page.selectOption('#practice-source','dialogue_round');
    await page.selectOption('#practice-quality','all');
    await page.locator('#practice-search').fill('不可能匹配的问题不可能匹配的问题');
    assert.equal(await page.locator('#practice-exercise option').count(),0);
    await page.locator('#practice-search').fill('');
    const downloaded=page.waitForEvent('download');await page.locator('#export-exercises').click();
    const download=await downloaded;
    const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(exported.exercises.filter(e=>e.source_kind==='dialogue_round').length,expected.length);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.goto(target+'#round='+encodeURIComponent(drill.round_id),{waitUntil:'networkidle'});
    assert.equal(await page.locator('#'+drill.round_id+' .practice-link').count(),1);
    await page.locator('#'+drill.round_id+' .practice-link').click();
    await page.waitForFunction(id=>document.getElementById('practice-exercise').value===id,drill.id);
    assert.equal(await page.locator('#practice-exercise').inputValue(),drill.id);
    await page.goto(target+'#exercise=%ZZ',{waitUntil:'networkidle'});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed',dialogueDrills:expected.length,checks:'answer concealment/reveal, draft persistence, source jump, next question, episode/quality filtering, legacy examples, empty search, JSON export, round-to-exercise deep link, malformed hash, mobile overflow'}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
